-- 04_分析.sql —— SQL 分析（在 MySQL Workbench 里打开，先跑完 03_导入MySQL.py 再运行）
-- 用法：Workbench 左上角双击 jobs 库使其变粗（选中），然后逐段选中查询按 Ctrl+Enter

USE jobs;

-- ════════════════════════════════════════════════════════════════
-- 查询 1：各城市的岗位数量与平均薪资
-- GROUP BY 相当于 split-apply-combine：按城市拆组 → 每组算聚合 → 拼回一张表
-- 过滤聚合结果用 HAVING 而不是 WHERE：SQL 按 FROM → WHERE → GROUP BY → HAVING
--   → SELECT → ORDER BY 的顺序执行，WHERE 执行时还没分组
-- ════════════════════════════════════════════════════════════════
SELECT 城市,
       COUNT(*)               AS 岗位数,
       ROUND(AVG(薪资中值), 1) AS 平均薪资_千
FROM job_postings
GROUP BY 城市
HAVING COUNT(*) >= 10          -- 样本太小的城市没有统计代表性
ORDER BY 岗位数 DESC;

-- ════════════════════════════════════════════════════════════════
-- 查询 2：学历要求分布 + 占比
-- 分母是全表总数，标量子查询只会算一次
-- ════════════════════════════════════════════════════════════════
SELECT 学历要求,
       COUNT(*) AS 岗位数,
       ROUND(COUNT(*) / (SELECT COUNT(*) FROM job_postings) * 100, 1) AS 占比百分比
FROM job_postings
GROUP BY 学历要求
ORDER BY 岗位数 DESC;

-- ════════════════════════════════════════════════════════════════
-- 查询 3：经验要求 vs 平均薪资（"工作几年最值钱"）
-- ORDER BY 里可以直接引用聚合函数
-- ════════════════════════════════════════════════════════════════
SELECT 经验要求,
       COUNT(*)               AS 岗位数,
       ROUND(AVG(薪资中值), 1) AS 平均薪资_千
FROM job_postings
GROUP BY 经验要求
ORDER BY 平均薪资_千 DESC;

-- ════════════════════════════════════════════════════════════════
-- 查询 4：岗位类别 vs 平均薪资（哪类数据岗更值钱：分析 / 工程 / 算法 / BI）
-- ════════════════════════════════════════════════════════════════
SELECT 岗位类别,
       COUNT(*)               AS 岗位数,
       ROUND(AVG(薪资中值), 1) AS 平均薪资_千
FROM job_postings
GROUP BY 岗位类别
ORDER BY 平均薪资_千 DESC;

-- ════════════════════════════════════════════════════════════════
-- 查询 5：技能词频的纯 SQL 写法
-- LIKE 返回 1/0，SUM 一下就是"出现的岗位数"，相当于一列长表转成一行宽表
-- ════════════════════════════════════════════════════════════════
SELECT SUM(职位描述 LIKE '%SQL%')    AS 要求SQL的岗位数,
       SUM(职位描述 LIKE '%Python%') AS 要求Python的岗位数,
       SUM(职位描述 LIKE '%Excel%')  AS 要求Excel的岗位数,
       SUM(职位描述 LIKE '%Hadoop%') AS 要求Hadoop的岗位数,
       SUM(职位描述 LIKE '%SPSS%')   AS 要求SPSS的岗位数,
       COUNT(*)                      AS 总岗位数
FROM job_postings;

-- ════════════════════════════════════════════════════════════════
-- 查询 6（进阶）：平均薪资高于全站平均的城市
-- HAVING 里可以直接嵌子查询做比较
-- ════════════════════════════════════════════════════════════════
SELECT 城市,
       ROUND(AVG(薪资中值), 1) AS 平均薪资_千
FROM job_postings
GROUP BY 城市
HAVING AVG(薪资中值) > (SELECT AVG(薪资中值) FROM job_postings)
ORDER BY 平均薪资_千 DESC;

-- ════════════════════════════════════════════════════════════════
-- 查询 7（进阶）：只看北京，各学历的平均薪资
-- WHERE 是行级过滤，在分组前执行
-- ════════════════════════════════════════════════════════════════
SELECT 学历要求,
       COUNT(*)               AS 岗位数,
       ROUND(AVG(薪资中值), 1) AS 平均薪资_千
FROM job_postings
WHERE 城市 = '北京'
GROUP BY 学历要求
ORDER BY 平均薪资_千 DESC;
